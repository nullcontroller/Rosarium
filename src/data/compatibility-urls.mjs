export function compatibilityDestination(record, current) {
  let fragment; try { fragment = decodeURIComponent(current.hash.slice(1)); } catch { fragment = ""; }
  const target = new URL(record.fragments[fragment] || record.to, current.origin);
  for (const key of new Set(current.searchParams.keys())) if (!target.searchParams.has(key)) for (const value of current.searchParams.getAll(key)) target.searchParams.append(key,value);
  if (!record.fragments[fragment] && !target.hash) target.hash = current.hash;
  return target;
}
export function resolveCompatibilityHref(href) {
  const source = new URL(href, 'https://rosarium-tech.com');
  if (source.origin !== 'https://rosarium-tech.com') return href;
  const record = compatibilityUrls.find(record => record.from === source.pathname);
  if (!record) return href;
  const target = compatibilityDestination(record, source);
  return target.pathname+target.search+target.hash;
}
